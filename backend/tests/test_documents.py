async def test_new_version_replaces_chunks(client, ingestor):
    admin = await register_org(client)
    doc = (await upload(client, admin, "policy.txt", b"Old rule: offices close at 5pm.")).json()
    await drain(ingestor)

    response = await client.post(
        f"{API}/documents/{doc['id']}/versions",
        headers=bearer(admin.token),
        files={"file": ("policy-v2.txt", b"New rule: offices close at 6pm.", "text/plain")},
    )
    assert response.status_code == 200, response.text
    body = response.json()
    assert body["current_version"] == 2
    assert body["status"] == "queued"
    assert [v["version"] for v in body["versions"]] == [2, 1]

    await drain(ingestor)
    chunks = (
        await client.get(f"{API}/documents/{doc['id']}/chunks", headers=bearer(admin.token))
    ).json()["items"]
    assert len(chunks) == 1
    assert "6pm" in chunks[0]["content"]

    old = await client.get(
        f"{API}/documents/{doc['id']}/download?version=1", headers=bearer(admin.token)
    )
    assert old.content == b"Old rule: offices close at 5pm."


