async def test_delete_removes_rows_files_and_is_audited(client, ingestor, settings):
    admin = await register_org(client)
    doc = (await upload(client, admin)).json()
    await drain(ingestor)
    assert any(Path(settings.storage_dir).rglob("original.txt"))

    response = await client.delete(f"{API}/documents/{doc['id']}", headers=bearer(admin.token))
    assert response.status_code == 204
    assert (
        await client.get(f"{API}/documents/{doc['id']}", headers=bearer(admin.token))
    ).status_code == 404
    assert await _count(ingestor, DocumentChunk) == 0
    assert await _count(ingestor, IngestionJob) == 0
    assert not any(Path(settings.storage_dir).rglob("original.txt"))

    logs = (await client.get(f"{API}/audit-logs", headers=bearer(admin.token))).json()["items"]
    actions = [entry["action"] for entry in logs]
    assert "document.deleted" in actions and "document.uploaded" in actions


async def test_list_filters_and_counts(client, ingestor):
    admin = await register_org(client)
    await upload(client, admin, "alpha-report.txt", b"Alpha")
    await drain(ingestor)
    await upload(client, admin, "beta-report.txt", b"Beta")
    await upload(client, admin, "gamma.txt", b"Gamma")
    headers = bearer(admin.token)

    page = (await client.get(f"{API}/documents", headers=headers)).json()
    assert page["total"] == 3
    assert page["status_counts"] == {"ready": 1, "queued": 2}
    assert page["items"][0]["title"] == "gamma"  # newest first

    queued = (await client.get(f"{API}/documents?status=queued", headers=headers)).json()
    assert queued["total"] == 2
    search = (await client.get(f"{API}/documents?q=report", headers=headers)).json()
    assert {d["title"] for d in search["items"]} == {"alpha-report", "beta-report"}
    # LIKE wildcards in the search box are treated literally.
    assert (await client.get(f"{API}/documents?q=%25", headers=headers)).json()["total"] == 0
    paged = (await client.get(f"{API}/documents?limit=1&offset=1", headers=headers)).json()
    assert len(paged["items"]) == 1 and paged["total"] == 3
