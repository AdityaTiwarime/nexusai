async def test_min_role_hides_documents_from_lower_roles(client):
    admin = await register_org(client)
    manager = await add_user(client, admin, "mgr@acme.com", "manager")
    employee = await add_user(client, admin, "emp@acme.com", "employee")
    secret = (
        await upload(client, admin, "salaries.txt", b"Salary bands", min_role="org_admin")
    ).json()
    managers = (await upload(client, manager, "plan.txt", b"Team plan", min_role="manager")).json()

    def ids(response):
        return {d["id"] for d in response.json()["items"]}

    listed = ids(await client.get(f"{API}/documents", headers=bearer(employee.token)))
    assert listed == set()
    listed = ids(await client.get(f"{API}/documents", headers=bearer(manager.token)))
    assert listed == {managers["id"]}
    listed = ids(await client.get(f"{API}/documents", headers=bearer(admin.token)))
    assert listed == {secret["id"], managers["id"]}

    # Hidden documents look exactly like missing ones.
    for path in ("", "/chunks", "/download"):
        url = f"{API}/documents/{secret['id']}{path}"
        assert (await client.get(url, headers=bearer(manager.token))).status_code == 404
        assert (await client.get(url, headers=bearer(employee.token))).status_code == 404


