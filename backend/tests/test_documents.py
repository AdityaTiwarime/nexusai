POLICY = (
    "# Remote work policy\n\n"
    "Employees may work from home on Fridays.\n\n"
    "## Equipment\n\nThe company provides a laptop and a monitor."
)


async def _count(ingestor, model, **filters) -> int:
    async with ingestor.sessions() as session:
        query = select(func.count()).select_from(model)
        for column, value in filters.items():
            query = query.where(getattr(model, column) == value)
        return await session.scalar(query)


async def test_upload_is_queued_then_processed_by_the_worker(client, ingestor):
    admin = await register_org(client)
    response = await upload(client, admin, "policy.md", POLICY.encode())
    assert response.status_code == 201, response.text
    body = response.json()
    assert body["status"] == "queued"
    assert body["title"] == "policy"
    assert body["file_type"] == "md"
    assert body["versions"][0]["version"] == 1
    assert body["uploaded_by_email"] == admin.email

    assert await drain(ingestor) == 1
    doc = (await client.get(f"{API}/documents/{body['id']}", headers=bearer(admin.token))).json()
    assert doc["status"] == "ready"
    assert doc["chunk_count"] >= 1
    assert doc["error"] is None
    assert doc["processed_at"] is not None

    chunks = (
        await client.get(f"{API}/documents/{body['id']}/chunks", headers=bearer(admin.token))
    ).json()
    assert chunks["total"] == doc["chunk_count"]
    assert "work from home on Fridays" in chunks["items"][0]["content"]

    async with ingestor.sessions() as session:
        chunk = await session.scalar(select(DocumentChunk))
        assert len(chunk.embedding) == 1536
        assert chunk.embedding_model.startswith("hashing")
        # tsvector is generated by PostgreSQL from the content.
        assert "friday" in str(chunk.tsv)


