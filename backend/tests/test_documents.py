async def test_invalid_files_are_rejected_and_nothing_is_stored(client, ingestor, settings):
    admin = await register_org(client)
    for filename, data, message in [
        ("virus.exe", b"MZ...", "Unsupported file type"),
        ("fake.pdf", b"not a pdf", "not a PDF"),
        ("empty.txt", b"", "empty"),
    ]:
        response = await upload(client, admin, filename, data)
        assert response.status_code == 422, filename
        assert message in response.json()["detail"]
    assert await _count(ingestor, IngestionJob) == 0
    storage = Path(settings.storage_dir)
    assert not any(p.is_file() for p in storage.rglob("*")) if storage.exists() else True


