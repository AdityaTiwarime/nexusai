"""File storage for uploaded documents.

A small interface so the local-disk implementation used in development and
docker-compose can be swapped for S3 (Phase 10) without touching callers.
Keys are generated by NexusAI, never taken from user-supplied filenames, so a
malicious filename like "../../etc/passwd" can't escape the storage directory.
"""

import os
import shutil
import tempfile
from pathlib import Path
from typing import Protocol


class Storage(Protocol):
    def put(self, key: str, data: bytes) -> None: ...
    def get(self, key: str) -> bytes: ...
    def delete_prefix(self, prefix: str) -> None: ...
    def exists(self, key: str) -> bool: ...


class LocalStorage:
    def __init__(self, base_dir: str) -> None:
        self.base = Path(base_dir).resolve()
        self.base.mkdir(parents=True, exist_ok=True)

    def _path(self, key: str) -> Path:
        path = (self.base / key).resolve()
        if self.base not in path.parents and path != self.base:
            raise ValueError("storage key escapes the storage directory")
        return path

    def put(self, key: str, data: bytes) -> None:
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        # Write to a temp file and rename: readers never see a half-written file.
        fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=".upload-")
        try:
            with os.fdopen(fd, "wb") as handle:
                handle.write(data)
            os.replace(tmp, path)
        except BaseException:
            Path(tmp).unlink(missing_ok=True)
            raise

    def get(self, key: str) -> bytes:
        return self._path(key).read_bytes()

    def exists(self, key: str) -> bool:
        return self._path(key).is_file()

    def delete_prefix(self, prefix: str) -> None:
        path = self._path(prefix)
        if path.is_dir():
            shutil.rmtree(path, ignore_errors=True)
        elif path.is_file():
            path.unlink(missing_ok=True)


def document_prefix(organization_id: object, document_id: object) -> str:
    return f"org/{organization_id}/doc/{document_id}"


def version_key(organization_id: object, document_id: object, version: int, file_type: str) -> str:
    return f"{document_prefix(organization_id, document_id)}/v{version}/original.{file_type}"
